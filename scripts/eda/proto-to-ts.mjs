#!/usr/bin/env node
// Generates the TypeScript descriptors of the EDA engine API (ROADMAP P1-2) from
// engines/eda/triage/api/proto/triage/eda/v1/engine.proto, for the codec in
// app/src/vs/triage/common/eda/protobuf.ts.
//
//   node scripts/eda/proto-to-ts.mjs           write app/src/vs/triage/common/eda/engineApi.generated.ts
//   node scripts/eda/proto-to-ts.mjs --check   fail if that file is out of date (CI)
//
// Understands the subset engine.proto uses: messages (not nested), enums, oneofs,
// `repeated`, and the scalar types the codec supports.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..', '..');
const protoFile = path.join(root, 'engines/eda/triage/api/proto/triage/eda/v1/engine.proto');
const outFile = path.join(root, 'app/src/vs/triage/common/eda/engineApi.generated.ts');
const SCALARS = new Set([
  'uint64',
  'uint32',
  'int32',
  'bool',
  'double',
  'float',
  'string',
  'bytes',
]);

export function parseProto(text) {
  const source = text.replace(/\/\/.*$/gm, '');
  const messages = [];
  const enums = new Map();
  const blocks = /(message|enum)\s+(\w+)\s*\{/g;
  let match;
  while ((match = blocks.exec(source))) {
    const [, kind, name] = match;
    let depth = 1;
    let i = blocks.lastIndex;
    while (depth > 0 && i < source.length) {
      if (source[i] === '{') depth += 1;
      else if (source[i] === '}') depth -= 1;
      i += 1;
    }
    const body = source.slice(blocks.lastIndex, i - 1);
    blocks.lastIndex = i;
    if (kind === 'enum') {
      const values = [...body.matchAll(/(\w+)\s*=\s*(\d+)\s*;/g)].map(([, n, v]) => [n, Number(v)]);
      enums.set(name, values);
      continue;
    }
    const fields = [];
    const flat = body.replace(/oneof\s+\w+\s*\{/g, '').replace(/\}/g, '');
    for (const [, repeated, type, field, number] of flat.matchAll(
      /(repeated\s+)?(\w+)\s+(\w+)\s*=\s*(\d+)\s*;/g,
    )) {
      fields.push({ name: field, type, number: Number(number), repeated: Boolean(repeated) });
    }
    messages.push({ name, fields });
  }
  return { messages, enums };
}

// get_board_3d -> getBoard3d, as protobuf-es names it.
const camel = (name) => name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

export function generate(text) {
  const { messages, enums } = parseProto(text);
  const names = new Set(messages.map((m) => m.name));
  const lines = [
    '/*---------------------------------------------------------------------------------------------',
    ' *  Triage. Licensed under GPL-3.0-or-later (see docs/PLAN.md §5).',
    ' *  GENERATED by scripts/eda/proto-to-ts.mjs from',
    ' *  engines/eda/triage/api/proto/triage/eda/v1/engine.proto. Do not edit.',
    ' *--------------------------------------------------------------------------------------------*/',
    '',
    "import { MessageDescriptor } from './protobuf.js';",
    '',
  ];
  for (const [name, values] of enums) {
    lines.push(`export const ${name} = {`);
    for (const [value, number] of values) lines.push(`\t${value}: ${number},`);
    lines.push('} as const;', '');
  }
  // Descriptors reference each other, so declare them first and fill them in after.
  for (const message of messages) {
    lines.push(
      `export const ${message.name}: MessageDescriptor = { name: '${message.name}', fields: [] };`,
    );
  }
  lines.push('');
  for (const message of messages) {
    lines.push(`(${message.name}.fields as unknown[]).push(`);
    for (const field of message.fields) {
      let type;
      if (SCALARS.has(field.type)) type = `'${field.type}'`;
      else if (enums.has(field.type)) type = "'enum'";
      else if (names.has(field.type)) type = field.type;
      else throw new Error(`${message.name}.${field.name}: unknown type ${field.type}`);
      lines.push(
        `\t{ name: '${camel(field.name)}', number: ${field.number}, type: ${type}${field.repeated ? ', repeated: true' : ''} },`,
      );
    }
    lines.push(');');
  }
  lines.push('');
  return lines.join('\n');
}

if (import.meta.filename === path.resolve(process.argv[1] ?? '')) {
  const output = generate(readFileSync(protoFile, 'utf8'));
  if (process.argv.includes('--check')) {
    const current = readFileSync(outFile, 'utf8');
    if (current !== output) {
      console.error(
        `${path.relative(root, outFile)} is out of date: run node scripts/eda/proto-to-ts.mjs`,
      );
      process.exit(1);
    }
    console.log(`${path.relative(root, outFile)} is up to date.`);
  } else {
    writeFileSync(outFile, output);
    console.log(`Wrote ${path.relative(root, outFile)}.`);
  }
}
