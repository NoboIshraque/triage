#!/usr/bin/env python3
"""Draws Triage's placeholder app icon (ROADMAP P0-2) with Pillow.

Writes the files that replace VS Code's icons in the app build (app/resources/
mirrors upstream's resources/ folder; app/build.mjs copies it over the checkout),
and the SVG overlays that replace VS Code's logos inside the workbench (ROADMAP
P0-9: title bar icon, empty-editor watermark, the Agents window's logo):

    python3 scripts/branding/placeholder_icons.py             # PNG, ICO and SVG
    python3 scripts/branding/placeholder_icons.py --svg-only  # SVG overlays only

A real icon replaces this before v1.0 (P8). The design: a teal rounded square
with a white "T" and an amber dot, readable at 16 px.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app" / "resources"
SRC = ROOT / "app" / "src" / "vs"
TEAL = (15, 118, 110, 255)
WHITE = (255, 255, 255, 255)
AMBER = (245, 158, 11, 255)
SUPERSAMPLE = 4

# The design in unit coordinates (0..1), shared by the PNG and the SVGs.
SQUARE = (0.06, 0.06, 0.94, 0.94, 0.2)  # x0, y0, x1, y1, corner radius
BAR = (0.22, 0.24, 0.78, 0.39)  # the T's bar
STEM = (0.425, 0.39, 0.575, 0.78)  # the T's stem, below the bar
CORNER = 0.05  # the T's corner radius
DOT = (0.72, 0.70, 0.075)  # centre x, centre y, radius


def draw(size: int):
    from PIL import Image, ImageDraw  # only the PNG and ICO files need Pillow

    s = size * SUPERSAMPLE
    image = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(image)
    margin = round(s * 0.06)
    d.rounded_rectangle((margin, margin, s - margin, s - margin), radius=round(s * 0.2), fill=TEAL)
    bar = round(s * 0.15)
    top = round(s * 0.24)
    d.rounded_rectangle((round(s * 0.22), top, round(s * 0.78), top + bar), radius=bar // 3, fill=WHITE)
    d.rounded_rectangle((round(s * 0.5) - bar // 2, top, round(s * 0.5) + bar // 2, round(s * 0.78)),
                        radius=bar // 3, fill=WHITE)
    r = round(s * 0.075)
    cx, cy = round(s * 0.72), round(s * 0.7)
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=AMBER)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def _n(value: float) -> str:
    return f"{value:.2f}".rstrip("0").rstrip(".")


def rounded_rect(x0, y0, x1, y1, r, top=True) -> str:
    """An SVG path for a rounded rectangle (square top corners when top=False)."""
    if top:
        start = f"M{_n(x0 + r)} {_n(y0)}H{_n(x1 - r)}A{_n(r)} {_n(r)} 0 0 1 {_n(x1)} {_n(y0 + r)}"
    else:
        start = f"M{_n(x0)} {_n(y0)}H{_n(x1)}"
    end = (f"V{_n(y0 + r)}A{_n(r)} {_n(r)} 0 0 1 {_n(x0 + r)} {_n(y0)}Z" if top else f"V{_n(y0)}Z")
    return (f"{start}V{_n(y1 - r)}A{_n(r)} {_n(r)} 0 0 1 {_n(x1 - r)} {_n(y1)}"
            f"H{_n(x0 + r)}A{_n(r)} {_n(r)} 0 0 1 {_n(x0)} {_n(y1 - r)}{end}")


def circle(cx, cy, r) -> str:
    return (f"M{_n(cx - r)} {_n(cy)}A{_n(r)} {_n(r)} 0 1 0 {_n(cx + r)} {_n(cy)}"
            f"A{_n(r)} {_n(r)} 0 1 0 {_n(cx - r)} {_n(cy)}Z")


def shapes(scale: float, dx: float = 0, dy: float = 0):
    """The square, the T (bar and stem, which touch but don't overlap) and the dot."""
    def box(b):
        return [dx + b[0] * scale, dy + b[1] * scale, dx + b[2] * scale, dy + b[3] * scale]
    square = rounded_rect(*box(SQUARE[:4]), SQUARE[4] * scale)
    bar = rounded_rect(*box(BAR), CORNER * scale)
    stem = rounded_rect(*box(STEM), CORNER * scale, top=False)
    dot = circle(dx + DOT[0] * scale, dy + DOT[1] * scale, DOT[2] * scale)
    return square, bar + stem, dot


def icon_svg() -> str:
    square, t, dot = shapes(1024)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">'
            f'<path fill="#0f766e" d="{square}"/><path fill="#fff" d="{t}"/>'
            f'<path fill="#f59e0b" d="{dot}"/></svg>\n')


def silhouette(scale: float, dx: float = 0, dy: float = 0) -> str:
    """One path: the square with the T and the dot cut out (even-odd fill)."""
    return "".join(shapes(scale, dx, dy))


def letterpress_svg(attrs: str, fill: str = "") -> str:
    # Upstream's letterpress is 260 x 260; the icon fills the same 228 px band.
    path = silhouette(228 / 0.88, 16 - 0.06 * 228 / 0.88, 16 - 0.06 * 228 / 0.88)
    return (f'<svg width="260" height="260" viewBox="0 0 260 260" {attrs} '
            f'xmlns="http://www.w3.org/2000/svg"><path fill-rule="evenodd" {fill}d="{path}"/></svg>\n')


def logo_path_ts() -> str:
    # The Agents window draws the logo from this path in a 96 x 96 box (6..90).
    path = silhouette(84 / 0.88, 6 - 0.06 * 84 / 0.88, 6 - 0.06 * 84 / 0.88)
    return ("/*---------------------------------------------------------------------------------------------\n"
            " *  Triage. Licensed under GPL-3.0-or-later (see docs/PLAN.md §5).\n"
            " *  Replaces VS Code's logo silhouette (ROADMAP P0-9). Generated by\n"
            " *  scripts/branding/placeholder_icons.py; draw it with fill-rule evenodd.\n"
            " *--------------------------------------------------------------------------------------------*/\n\n"
            "// Triage's icon: a rounded square with the T and the dot cut out.\n"
            f"export const VSCODE_LOGO_PATH = '{path}';\n")


def write_svgs() -> None:
    files = {
        SRC / "workbench" / "browser" / "media" / "code-icon.svg": icon_svg(),
        SRC / "sessions" / "browser" / "media" / "vscode-icon.svg": icon_svg(),
        SRC / "sessions" / "contrib" / "aquarium" / "browser" / "vscodeLogoPath.ts": logo_path_ts(),
    }
    letterpress = SRC / "workbench" / "browser" / "parts" / "editor" / "media"
    files[letterpress / "letterpress-light.svg"] = letterpress_svg('opacity="0.1"')
    files[letterpress / "letterpress-dark.svg"] = letterpress_svg('opacity="0.3"')
    files[letterpress / "letterpress-hcLight.svg"] = letterpress_svg('fill="none"', 'fill="#D9D9D9" ')
    files[letterpress / "letterpress-hcDark.svg"] = letterpress_svg('fill="none"', 'fill="#3C3C3C" ')
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, newline="\n")
        print(path.relative_to(ROOT))


def main() -> None:
    write_svgs()
    if "--svg-only" in sys.argv[1:]:
        return
    (OUT / "linux").mkdir(parents=True, exist_ok=True)
    (OUT / "win32").mkdir(parents=True, exist_ok=True)
    draw(1024).save(OUT / "linux" / "code.png", optimize=True)
    draw(70).save(OUT / "win32" / "code_70x70.png", optimize=True)
    draw(150).save(OUT / "win32" / "code_150x150.png", optimize=True)
    big = draw(256)
    big.save(OUT / "win32" / "code.ico",
             sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    for path in sorted(OUT.rglob("*")):
        if path.is_file():
            print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
