#!/usr/bin/env node
// Builds the phone app (ROADMAP PC-3) into companion/web/dist/, a static site:
// TypeScript compiled to ES modules with the TypeScript compiler (no bundler,
// DV-46), the static files, jsQR (the QR decoder iOS needs), the web app
// manifest, config.json (the relay, from TRIAGE_COMPANION_RELAY) and a service
// worker that caches the whole app under a version made from its files' hashes.
//
//   node companion/web/build.mjs
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cpSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const here = import.meta.dirname;
const dist = path.join(here, 'dist');
const require = createRequire(import.meta.url);

rmSync(dist, { recursive: true, force: true });
const tsc = require.resolve('typescript/bin/tsc');
const compiled = spawnSync(process.execPath, [tsc, '-p', path.join(here, 'tsconfig.build.json')], {
  stdio: 'inherit',
});
if (compiled.status !== 0) process.exit(compiled.status ?? 1);

cpSync(path.join(here, 'static'), dist, { recursive: true });
mkdirSync(path.join(dist, 'vendor'), { recursive: true });
cpSync(require.resolve('jsqr/dist/jsQR.js'), path.join(dist, 'vendor', 'jsQR.js'));

const pkg = JSON.parse(readFileSync(path.join(here, 'package.json'), 'utf8'));
const manifest = {
  name: 'Triage',
  short_name: 'Triage',
  description:
    'The schematic, board, 3D model and simulation of the Triage project open on your laptop.',
  id: './',
  start_url: './',
  scope: './',
  display: 'standalone',
  orientation: 'any',
  background_color: '#0b1220',
  theme_color: '#1e293b',
  icons: [
    { src: './icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: './icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: './icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    { src: './icons/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
  ],
};
writeFileSync(path.join(dist, 'manifest.webmanifest'), `${JSON.stringify(manifest, null, 2)}\n`);
const relay = process.env['TRIAGE_COMPANION_RELAY'] ?? '';
writeFileSync(path.join(dist, 'config.json'), `${JSON.stringify(relay ? { relay } : {})}\n`);
// GitHub Pages: serve files and folders as they are (no Jekyll).
writeFileSync(path.join(dist, '.nojekyll'), '');

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const file = path.join(dir, name);
    return statSync(file).isDirectory() ? files(file) : [file];
  });
}

// The offline shell: everything but config.json (fetched fresh) and source maps.
const shell = files(dist)
  .map((file) => path.relative(dist, file).split(path.sep).join('/'))
  .filter((file) => !file.endsWith('.map') && file !== 'config.json' && !file.startsWith('.'))
  .sort();
const hash = createHash('sha256');
for (const file of shell) hash.update(file).update(readFileSync(path.join(dist, file)));
const version = `${pkg.version}-${hash.digest('hex').slice(0, 12)}`;
const precache = ['./', ...shell.map((file) => `./${file}`)];
writeFileSync(
  path.join(dist, 'sw.js'),
  `// The Triage phone app's service worker (generated by companion/web/build.mjs).
// Caches the app so it opens without the internet once installed; a new version
// replaces the old cache. config.json and the laptop's connections aren't cached.
const VERSION = ${JSON.stringify(version)};
const SHELL = ${JSON.stringify(precache, null, 2)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(VERSION).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== VERSION).map((key) => caches.delete(key)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.endsWith('/config.json')) {
    return;
  }
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then((hit) => hit || fetch(event.request)),
  );
});
`,
);
writeFileSync(path.join(dist, 'version.json'), `${JSON.stringify({ version })}\n`);
console.log(`Built companion/web/dist (${shell.length} files, version ${version})`);
