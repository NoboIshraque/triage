#!/usr/bin/env node
// Generates src/generated/avr-decoder.ts from avr8js's instruction decoder
// (node_modules/avr8js/dist/esm/cpu/instruction.js): the same instruction bodies,
// dispatched through a 64K table indexed by opcode instead of a chain of up to 86
// comparisons, so the AVR unit runs several times faster (ROADMAP P3-2).
// test/avr-decoder.test.ts checks every opcode against avr8js's own decoder.
//
//   node sim/scripts/avr-decoder.mjs           write the file
//   node sim/scripts/avr-decoder.mjs --check   fail if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const here = import.meta.dirname;
const require = createRequire(path.join(here, '..', 'package.json'));
const pkgDir = path.dirname(require.resolve('avr8js/package.json'));
const version = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const source = readFileSync(path.join(pkgDir, 'dist', 'esm', 'cpu', 'instruction.js'), 'utf8');

const start = source.indexOf('export function avrInstruction(cpu) {');
const helper = source.slice(source.indexOf('function isTwoWordInstruction'), start).trim();
const body = source.slice(start);
const epilogue = '    cpu.pc = (cpu.pc + 1) % cpu.progMem.length;\n    cpu.cycles++;\n}';
if (!body.includes(epilogue))
  throw new Error('avr8js changed its decoder epilogue; update this script');

// Split the if / else-if chain into (condition, body) pairs.
const lines = body.split('\n');
const branches = [];
let current;
let pending; // a condition that spans several lines
for (const line of lines.slice(2)) {
  if (pending !== undefined) {
    pending += ` ${line.trim()}`;
    if (line.endsWith(') {')) {
      current = { condition: pending.slice(0, -3), body: [] };
      branches.push(current);
      pending = undefined;
    }
    continue;
  }
  const head = /^ {4}(?:else )?if \((.*)$/.exec(line);
  if (head) {
    if (line.endsWith(') {')) {
      current = { condition: head[1].slice(0, -3), body: [] };
      branches.push(current);
    } else {
      current = undefined;
      pending = head[1];
    }
  } else if (line === '    }') {
    current = undefined;
  } else if (current) {
    current.body.push(line.slice(4));
  } else if (line.startsWith('    cpu.pc =')) {
    break;
  }
}
if (branches.length < 80) throw new Error(`found only ${branches.length} instructions`);

// The table: for every opcode, the first branch whose condition holds (0 = none).
const table = new Uint8Array(65536);
const tests = branches.map((b) => new Function('opcode', `return ${b.condition};`));
for (let opcode = 0; opcode < 65536; opcode++) {
  const i = tests.findIndex((test) => test(opcode));
  table[opcode] = i + 1;
}
// Run-length encode the table to keep the file small.
const runs = [];
for (let i = 0; i < table.length;) {
  let j = i;
  while (j < table.length && table[j] === table[i]) j++;
  runs.push(j - i, table[i]);
  i = j;
}

const out = `// Generated by sim/scripts/avr-decoder.mjs from avr8js ${version}'s
// dist/esm/cpu/instruction.js (MIT, Copyright (c) Uri Shaked and contributors).
// Do not edit: run \`node sim/scripts/avr-decoder.mjs\` after updating avr8js.
/* eslint-disable */
// @ts-nocheck
import type { CPU } from 'avr8js';

export const AVR8JS_VERSION = '${version}';

${helper}

type Handler = (cpu: CPU, opcode: number) => void;

const handlers: Handler[] = [
  () => {},
${branches
  .map(
    (b) =>
      `  (cpu, opcode) => {\n    // ${b.condition}\n${b.body.map((l) => (l ? `  ${l}` : l)).join('\n')}\n  },`,
  )
  .join('\n')}
];

const RUNS = [${runs.join(',')}];
const TABLE = new Uint8Array(65536);
for (let i = 0, at = 0; i < RUNS.length; i += 2) {
  TABLE.fill(RUNS[i + 1], at, at + RUNS[i]);
  at += RUNS[i];
}

/** avr8js's avrInstruction, dispatched by table. */
export function avrInstructionFast(cpu: CPU): void {
  const opcode = cpu.progMem[cpu.pc];
  handlers[TABLE[opcode]](cpu, opcode);
  cpu.pc = (cpu.pc + 1) % cpu.progMem.length;
  cpu.cycles++;
}
`;
const file = path.join(here, '..', 'src', 'generated', 'avr-decoder.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== out) {
    console.error(`${file} is out of date: run node sim/scripts/avr-decoder.mjs`);
    process.exit(1);
  }
  console.log(`${path.relative(process.cwd(), file)} is up to date (avr8js ${version})`);
} else {
  writeFileSync(file, out);
  console.log(
    `Wrote ${path.relative(process.cwd(), file)}: ${branches.length} instructions, ${runs.length / 2} table runs`,
  );
}
