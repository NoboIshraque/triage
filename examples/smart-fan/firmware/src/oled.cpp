bool begin(uint8_t address) {
  addr = address;
  Wire.begin();
  Wire.setClock(400000);
  Wire.beginTransmission(addr);
  if (Wire.endTransmission() != 0)
    return false;
  static const uint8_t init[] = {
      0xAE,       // display off
      0xD5, 0x80, // clock
      0xA8, 0x3F, // 64 rows
      0xD3, 0x00, // no offset
      0x40,       // start line 0
      0x8D, 0x14, // charge pump on
      0x20, 0x00, // horizontal addressing
      0xA1,       // columns mirrored (module wiring)
      0xC8,       // rows top to bottom
      0xDA, 0x12, // COM pins
      0x81, 0xCF, // contrast
      0xD9, 0xF1, // pre-charge
      0xDB, 0x40, // VCOMH
      0xA4,       // show RAM
      0xA6,       // not inverted
  };
  for (uint8_t c : init)
    command(c);
  clear();
  command(0xAF); // display on
  return true;
}

void clear() {
  window(0, 0);
  for (uint16_t i = 0; i < 1024; i += 16) {
    Wire.beginTransmission(addr);
    Wire.write(0x40); // data follows
    for (uint8_t k = 0; k < 16; k++)
      Wire.write(0x00);
    Wire.endTransmission();
  }
}

void text(uint8_t column, uint8_t line, const char *s, uint8_t width) {
  window(column * 6, line);
  uint8_t written = 0;
  while (*s || written < width) {
    char ch = *s ? *s++ : ' ';
    if (ch < 0x20 || ch > 0x7E)
      ch = '?';
    Wire.beginTransmission(addr);
    Wire.write(0x40);
    for (uint8_t k = 0; k < 5; k++)
      Wire.write(pgm_read_byte(&FONT[ch - 0x20][k]));
    Wire.write(0x00); // one blank column between characters
    Wire.endTransmission();
    written++;
  }
}

