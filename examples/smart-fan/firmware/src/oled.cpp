void command(uint8_t c) {
  Wire.beginTransmission(addr);
  Wire.write(0x00); // a command stream follows
  Wire.write(c);
  Wire.endTransmission();
}

void window(uint8_t column, uint8_t page) {
  command(0x21); // column range
  command(column);
  command(127);
  command(0x22); // page range
  command(page);
  command(7);
}

